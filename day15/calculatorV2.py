# creating add function 
def add(a, b):
    return a+b

# creating subtract function 
def subtract(a, b):
    return a-b

# creating multiply functions
def multiply(a, b):
    return a*b

if __name__ == "__main__":
    print(f"Addition: {add(10,2)}")
    print(f"Subtraction: {subtract(10,2)}")
    print(f"Multiplication: {multiply(10,2)}")